#!/usr/bin/env node
// Builds the Windows setup program from the pinned upstream source archive.
//
// The package is a source drop on purpose: the EFI image has to be linked against the
// target machine's own partitions, so a prebuilt binary would not work on any machine —
// including the one it was built on. What the setup program buys the reader is the
// checkout, the docs and the licence texts, in one click.
//
// Usage: node deploy/installer/build.mjs [--check]
//   --check   verify the pinned archive hash and the staged contents, build nothing

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");

// The pinned tag, commit and archive hash live in src/data/windows-package.json, which the
// site imports too. Keeping one copy means a bump cannot leave /windows claiming one version
// while the artifact it links is another.
const {
  version: VERSION,
  sourceCommit: SOURCE_COMMIT,
  sourceSha256: ARCHIVE_SHA256,
} = JSON.parse(readFileSync(join(ROOT, "src/data/windows-package.json"), "utf8"));

const ARCHIVE_URL = `https://codeload.github.com/impacifist/Windows-GPU-UNLOCK/zip/refs/tags/v${VERSION}`;
const BUILD = join(ROOT, "deploy/installer/.build");
const ARCHIVE = join(BUILD, `upstream-v${VERSION}.zip`);
const STAGE = join(BUILD, "stage");
const OUT_DIR = join(ROOT, "public/downloads");
const OUT_NAME = `GPU-Unlock-Windows-${VERSION}-Setup.exe`;

// Anything in the upstream tree that must not ship: .git and the CI definitions would be
// noise inside a source drop.
const EXCLUDE = new Set([".git", ".github"]);

// release/EFI/BOOT/BOOTX64.EFI is the image built for the maintainer's own partitions. Its
// hash is documented, but it is not portable: the unlock is tied to one PCI/PROM/MMIO
// profile and one partition layout, so a reader who installs it onto a different machine is
// running an image that does not match their hardware. The archive keeps the sources and the
// build scripts; the compiled output is dropped here so the installer cannot hand it out.
const DROP_PATHS = ["release"];

const checkOnly = process.argv.includes("--check");

const sha256 = (path) => createHash("sha256").update(readFileSync(path)).digest("hex");

function fetchArchive() {
  if (existsSync(ARCHIVE) && sha256(ARCHIVE) === ARCHIVE_SHA256) {
    console.log(`archive ok  ${ARCHIVE}`);
    return;
  }
  mkdirSync(BUILD, { recursive: true });
  console.log(`download    ${ARCHIVE_URL}`);
  execFileSync("curl", ["-sSL", "--fail", "--max-time", "300", "-o", ARCHIVE, ARCHIVE_URL], {
    stdio: "inherit",
  });
  const got = sha256(ARCHIVE);
  if (got !== ARCHIVE_SHA256) {
    throw new Error(`archive hash mismatch\n  want ${ARCHIVE_SHA256}\n  got  ${got}`);
  }
}

function extract() {
  rmSync(STAGE, { recursive: true, force: true });
  mkdirSync(STAGE, { recursive: true });
  // unzip prompts before overwriting, which deadlocks a non-interactive build, so the
  // previous unpacking is removed rather than overwritten.
  const unpackRoot = join(BUILD, "unpacked");
  rmSync(unpackRoot, { recursive: true, force: true });
  execFileSync("unzip", ["-q", ARCHIVE, "-d", unpackRoot]);
  const unpacked = join(unpackRoot, `Windows-GPU-UNLOCK-${VERSION}`);
  if (!existsSync(unpacked)) {
    throw new Error(`unexpected archive layout: ${unpacked} is missing`);
  }
  for (const entry of readdirSync(unpacked)) {
    if (EXCLUDE.has(entry) || DROP_PATHS.includes(entry)) continue;
    execFileSync("cp", ["-R", join(unpacked, entry), join(STAGE, entry)]);
  }

  // The setup program shows the licence page from a plain-text file.
  const licence = readFileSync(join(STAGE, "LICENSE"), "utf8");
  writeFileSync(
    join(HERE, "licence.txt"),
    `upstream: https://github.com/impacifist/Windows-GPU-UNLOCK\n` +
      `tag: v${VERSION}\n` +
      `commit: ${SOURCE_COMMIT}\n\n` +
      `${licence}\n` +
      `\nNVIDIA firmware and driver files are NOT included and remain under NVIDIA's own\n` +
      `terms; see LICENSES/ in the installed tree.\n`,
  );
}

function verifyStage() {
  const count = (dir) => {
    let n = 0;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      n += entry.isDirectory() ? count(join(dir, entry.name)) : 1;
    }
    return n;
  };
  const files = count(STAGE);

  // The stage must be source only. The five firmware assets are generated by the reader from
  // their own card, and the compiled EFI is tied to one machine's partitions — neither is
  // useful to anyone else, and both are what a reader would otherwise flash by mistake.
  const offenders = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (/\.(bin|sys|dll|exe|efi)$/i.test(entry.name)) offenders.push(p.slice(STAGE.length + 1));
    }
  };
  walk(STAGE);

  for (const required of ["README.md", "LICENSE", "docs/GUIDE.en.md", "docs/HEADLESS.en.md", "internal-boot/Headless.ps1"]) {
    if (!existsSync(join(STAGE, required))) throw new Error(`stage is missing ${required}`);
  }
  if (offenders.length) {
    throw new Error(`stage contains binaries that must not be redistributed:\n  ${offenders.join("\n  ")}`);
  }
  console.log(`stage ok    ${files} files, source only — no firmware, no compiled EFI`);
}

function build() {
  mkdirSync(OUT_DIR, { recursive: true });
  const outfile = join(OUT_DIR, OUT_NAME);
  rmSync(outfile, { force: true });

  // A version bump renames the artifact, so the previous release would sit in the served
  // directory next to the new one, each with a valid .sha256 of its own. Nothing downstream
  // can tell which is current — the page links the new name, but the old file is still
  // downloadable, and the postbuild check passes for both. Remove releases it does not own.
  for (const name of readdirSync(OUT_DIR)) {
    const stale = /^GPU-Unlock-Windows-.+-Setup\.exe(\.sha256)?$/.test(name) &&
      name !== OUT_NAME && name !== `${OUT_NAME}.sha256`;
    if (!stale) continue;
    rmSync(join(OUT_DIR, name), { force: true });
    console.log(`removed     ${name} (not version ${VERSION})`);
  }

  console.log(`makensis    ${OUT_NAME}`);
  execFileSync(
    "makensis",
    [
      "-V2",
      `-DVERSION=${VERSION}`,
      `-DSTAGE=${STAGE}`,
      `-DOUTFILE=${outfile}`,
      join(HERE, "installer.nsi"),
    ],
    { stdio: "inherit", cwd: HERE },
  );

  const size = statSync(outfile).size;
  const digest = sha256(outfile);
  writeFileSync(
    join(OUT_DIR, `${OUT_NAME}.sha256`),
    `${digest}  ${OUT_NAME}\n`,
  );
  console.log(`built       ${outfile}`);
  console.log(`size        ${(size / 1024 / 1024).toFixed(2)} MiB`);
  console.log(`sha256      ${digest}`);

  // PE check: an NSIS output is a Windows PE, and a truncated build is the failure mode
  // that would otherwise only show up on the machine that runs it.
  const head = readFileSync(outfile).subarray(0, 2).toString("latin1");
  if (head !== "MZ") throw new Error("output is not a PE image");
  if (size < 1024 * 1024) throw new Error(`output is implausibly small (${size} bytes)`);
}

fetchArchive();
extract();
verifyStage();
if (checkOnly) {
  console.log("check only: skipping makensis");
} else {
  build();
}
